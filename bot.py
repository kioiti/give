# =========================================================

@client.event
async def on_ready():

    print(f"{client.user} 로그인 완료")

# =========================================================
# 메시지
# =========================================================

@client.event
async def on_message(message):

    if message.author == client.user:
        return

    content = message.content.strip()

    # =====================================================
    # 운빨
    # =====================================================

    if content == "!운빨":

        await message.channel.send(
            random.choice(luck)
        )

    # =====================================================
    # 오늘
    # =====================================================

    elif content == "!오늘":

        await message.channel.send(
            random.choice(daily)
        )

    # =====================================================
    # 확률
    # =====================================================
    elif content.startswith("!확률"):

        target = content[4:].strip()

        if not target:

            await message.channel.send(
                "사용법 : !확률 내용"
            )
            return

        percent = random.randint(0, 100)

        if percent <= 5:
            mood = "☠️ 멸망"

        elif percent <= 15:
            mood = "💀 억까 감지"

        elif percent <= 30:
            mood = "🪨 쉽지않음"

        elif percent <= 50:
            mood = "🌫 애매함"

        elif percent <= 70:
            mood = "✨ 가능성 있음"

        elif percent <= 85:
            mood = "🔥 좋은 흐름"

        elif percent <= 95:
            mood = "⚡ 개잘됨"

        else:
            mood = "👑 신의 영역"

        await message.channel.send(
            f"""
🎲 확률 분석 결과

📌 대상 : {target}
📈 확률 : {percent}%
{mood}
"""
        )
        
    # =====================================================
    # 사용법
    # =====================================================

    elif content == "!사용법":

        await message.channel.send(
"""
📖 사용 가능한 명령어

🎲 랜덤
!운빨
!오늘
!확률 내용
"""
        )

